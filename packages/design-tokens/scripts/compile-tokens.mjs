import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(here, "../src/tokens.json");
const outDir = path.resolve(here, "../generated");
const tokens = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const flat = {};

function visit(node, trail = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$") || key === "meta") continue;
    if (value && typeof value === "object" && "value" in value) flat[[...trail, key].join(".")] = value.value;
    else if (value && typeof value === "object") visit(value, [...trail, key]);
  }
}

visit(tokens);
const variable = (name) => `--ck-${name.replaceAll(".", "-")}`;
const baseEntries = Object.entries(flat).filter(([name]) => !name.startsWith("theme."));
const css = [
  ":root {",
  ...baseEntries.map(([name, value]) => `  ${variable(name)}: ${value};`),
  "}",
  "[data-theme='light'] {",
  ...Object.entries(tokens.theme.light).map(([name, token]) => `  --ck-theme-${name}: ${token.value};`),
  "}",
  "[data-theme='dark'] {",
  ...Object.entries(tokens.theme.dark).map(([name, token]) => `  --ck-theme-${name}: ${token.value};`),
  "}",
  "@media (prefers-reduced-motion: reduce) { :root { --ck-motion-duration-fast: 0ms; --ck-motion-duration-normal: 0ms; --ck-motion-duration-slow: 0ms; } }",
  "",
].join("\n");

const ts = `// Generated by compile-tokens.mjs. Do not edit.\nexport const designTokens = ${JSON.stringify(flat, null, 2)} as const;\nexport type DesignTokenName = keyof typeof designTokens;\n`;
const docs = ["# Signal Garden design tokens", "", `Generated from \`src/tokens.json\` (${Object.keys(flat).length} leaf tokens).`, "", "| Token | Value |", "| --- | --- |", ...Object.entries(flat).map(([key, value]) => `| \`${key}\` | \`${String(value).replaceAll("|", "\\|")}\` |`), ""].join("\n");
const manifest = { id: "signal-garden", name: tokens.meta.name, version: tokens.meta.version, generatedAt: new Date(0).toISOString(), themes: Object.keys(tokens.theme), tokenCount: Object.keys(flat).length, tokenCategories: Object.keys(tokens).filter((key) => !key.startsWith("$") && !["meta", "theme"].includes(key)), tokens: flat, source: "packages/design-tokens/src/tokens.json" };

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "tokens.css"), css);
fs.writeFileSync(path.join(outDir, "tokens.ts"), ts);
fs.writeFileSync(path.join(outDir, "tokens.md"), docs);
fs.writeFileSync(path.join(outDir, "design-system-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Compiled ${Object.keys(flat).length} tokens.`);
